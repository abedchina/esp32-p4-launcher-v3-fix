#!/usr/bin/env python3
"""Makes font_he.h: anti-aliased Hebrew + Latin glyphs (Arial) for the Hand Robot app.
    python apps/hand_robot/gen_font.py
Two sizes: small (regular 13 px) and big (bold 22 px). 8-bit alpha per pixel."""
import os
from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
FONTS = [("small", "C:/Windows/Fonts/arial.ttf", 13),
         ("big", "C:/Windows/Fonts/arialbd.ttf", 22)]
CHARS = [chr(c) for c in range(0x20, 0x7F)] + [chr(c) for c in range(0x5D0, 0x5EB)] + ["\u00b0", "\u00b7", "\u05f3"]

out = ["/* generated by gen_font.py - do not edit */", "#pragma once", "#include <stdint.h>", "",
       "typedef struct { uint16_t cp; int8_t adv, x, y; uint8_t w, h; uint32_t off; } glyph_t;",
       "typedef struct { const glyph_t *g; int n; const uint8_t *bits; int height, ascent; } font_t;", ""]

for name, path, size in FONTS:
    f = ImageFont.truetype(path, size)
    ascent, descent = f.getmetrics()
    bits = bytearray()
    glyphs = []
    for ch in CHARS:
        adv = int(round(f.getlength(ch)))
        box = f.getbbox(ch)
        if box[2] <= box[0] or box[3] <= box[1]:
            glyphs.append((ord(ch), adv, 0, 0, 0, 0, len(bits)))
            continue
        w, h = box[2] - box[0], box[3] - box[1]
        im = Image.new("L", (w, h), 0)
        ImageDraw.Draw(im).text((-box[0], -box[1]), ch, font=f, fill=255)
        glyphs.append((ord(ch), adv, box[0], box[1], w, h, len(bits)))
        bits += im.tobytes()
    out.append("static const uint8_t %s_bits[%d] = {" % (name, max(1, len(bits))))
    for i in range(0, len(bits), 32):
        out.append("    " + ",".join(str(b) for b in bits[i:i + 32]) + ",")
    out.append("};")
    out.append("static const glyph_t %s_glyphs[%d] = {" % (name, len(glyphs)))
    for g in glyphs:
        out.append("    {0x%04X, %d, %d, %d, %d, %d, %d}," % g)
    out.append("};")
    out.append("static const font_t font_%s = { %s_glyphs, %d, %s_bits, %d, %d };" %
               (name, name, len(glyphs), name, ascent + descent, ascent))
    out.append("")

open(os.path.join(HERE, "font_he.h"), "w", encoding="utf-8").write("\n".join(out))
print("font_he.h written")
